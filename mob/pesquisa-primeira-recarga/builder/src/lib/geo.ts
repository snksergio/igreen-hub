const pointInRing = (lon: number, lat: number, ring: Ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
};

export const isLand = (lon: number, lat: number) =>
  LAND.some((ring) => pointInRing(lon, lat, ring)) &&
  !SEA.some((ring) => pointInRing(lon, lat, ring));

export type Dot = { lon: number; lat: number };

/** Regular lon/lat lattice, filtered to land. */
export const landLattice = (
  step: number,
  latMin = -56,
  latMax = 78,
): Dot[] => {
  const dots: Dot[] = [];
  for (let lat = latMax; lat >= latMin; lat -= step) {
    for (let lon = -180; lon <= 180; lon += step) {
      if (isLand(lon, lat)) dots.push({ lon, lat });
    }
  }
  return dots;
};

/** Equirectangular projection into a fixed pixel box. */
export const project = (
  lon: number,
  lat: number,
  width: number,
  height: number,
  latMin = -56,
  latMax = 78,
) => ({
  x: ((lon + 180) / 360) * width,
  y: ((latMax - lat) / (latMax - latMin)) * height,
});

/** Lat/lon to a point on a unit sphere (y up, prime meridian toward +z). */
export const toSphere = (lon: number, lat: number, radius: number) => {
  const phi = (90 - lat) * (Math.PI / 180);
  const theta = (lon + 180) * (Math.PI / 180);
  return [
    -radius * Math.sin(phi) * Math.cos(theta),
    radius * Math.cos(phi),
    radius * Math.sin(phi) * Math.sin(theta),
  ] as [number, number, number];
};
